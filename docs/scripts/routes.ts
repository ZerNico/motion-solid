/**
 * Writes a route for each page of `src/pages.ts`, and removes the routes of pages that were
 * removed. Run with `pnpm routes`.
 */
import { readdir, rm, writeFile } from "node:fs/promises"
import { pages } from "../src/pages.ts"

const routes = new URL("../src/routes/", import.meta.url)
const slugs = new Set(pages.map((page) => page.slug))
// Routes under /docs that aren't pages.
const keep = new Set(["docs.tsx", "docs.index.tsx"])

for (const file of await readdir(routes)) {
    const slug = file.match(/^docs\.(.+)\.tsx$/)?.[1]
    if (slug && !keep.has(file) && !slugs.has(slug)) {
        await rm(new URL(file, routes))
    }
}

for (const { slug } of pages) {
    await writeFile(
        new URL(`docs.${slug}.tsx`, routes),
        `// Generated by \`pnpm routes\` from src/pages.ts.
import { createFileRoute } from "@tanstack/solid-router"
import { DocPage } from "../components/DocPage"
import { mdxComponents } from "../components/mdx"
import Content, { toc } from "../content/${slug}.mdx"
import { pageHead } from "../pages"

export const Route = createFileRoute("/docs/${slug}")({
    head: pageHead("${slug}"),
    component: () => (
        <DocPage toc={toc}>
            <Content components={mdxComponents} />
        </DocPage>
    ),
})
`
    )
}
